def percent(provided: set[str]) -> int:
    done = sum(1 for d in REQUIRED if d.key in provided)
    return round(100 * done / len(REQUIRED)) if REQUIRED else 0


def _praise(pct: int) -> str:
    if pct >= 100:
        return "🏆 <b>Отлично! Вы собрали полный пакет документов.</b>"
    if pct >= 75:
        return "👏 <b>Молодец! Собрано почти всё.</b>"
    if pct >= 50:
        return "👍 <b>Хорошее начало — половина пакета уже есть.</b>"
    return "📌 <b>Пакет пока неполный — но вы уже знаете, что просить у застройщика.</b>"


def conclusion(provided: set[str], pages: dict[str, tuple[int, int]],
               company: str = "", zhk: str = "") -> str:
    """Заключение для покупателя простым языком.

    provided — документы, собранные полностью; pages — {ключ: (принято фото, нужно фото)}.
    """
    pct = percent(provided)
    done = [d for d in REQUIRED if d.key in provided]
    partial = [d for d in REQUIRED if d.key not in provided and pages.get(d.key, (0, 0))[0]]
    missing = [d for d in REQUIRED if d.key not in provided and not pages.get(d.key, (0, 0))[0]]
    bar = "".join("🟩" if d.key in provided else "🟨" if d in partial else "⬜" for d in REQUIRED)

    lines = ["🏁 <b>Проверка завершена</b>"]
    if company or zhk:
        lines.append(f"🏗 {html.escape(company)} · {html.escape(zhk)}")
    lines += ["", _praise(pct), "",
              f"📊 Собрано: <b>{len(done)} из {len(REQUIRED)}</b> документов — <b>{pct}%</b>",
              bar, ""]

    if done:
        lines.append("✅ <b>Есть полностью</b>")
        lines += [f"• {d.title}" for d in done]
        lines.append("")
    if partial:
        lines.append("🟨 <b>Есть, но не все страницы</b>")
        for d in partial:
            got, need = pages[d.key]
            lines.append(f"• {d.title} — {got} из {need} стр.")
        lines.append("")
    if missing or partial:
        lines.append("⚠️ <b>На что обратить внимание</b>")
        for d in partial + missing:
            lines.append(f"• <b>{d.title}</b>\n   {d.risk}")
        lines.append("")

    lines.append("💡 <b>Важно:</b> наличие документа — это уже хорошо, но решает его "
                 "<b>содержание</b>. Фото показывает, что документ есть, а дальше каждую "
                 "строку должен изучить юрист.")
    lines.append("")

    if pct >= OFFER_THRESHOLD:
        lines.append(f"🎁 <b>Ваш бонус — скидка {DISCOUNT_PCT}% на юридическое сопровождение!</b>\n"
                     f"Мы {OFFER_SERVICES}. Вы оплачиваете только {CLIENT_PAYS_PCT}% стоимости.")
    else:
        left = len(REQUIRED) - len(done)
        lines.append(f"🎯 До бонуса не хватает: <b>{left}</b> док. Соберите все {len(REQUIRED)} "
                     f"полностью — и получите <b>скидку {DISCOUNT_PCT}%</b> на юридическое "
                     "сопровождение. Чем полнее пакет, тем безопаснее покупка.")
    return "\n".join(lines)
