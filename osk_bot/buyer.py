DOCS_BY_KEY = {d.key: d for d in DOCS}
REQUIRED = [d for d in DOCS if d.required]

# Порог, при котором предлагаем сопровождение со скидкой.
OFFER_THRESHOLD = 90


def percent(provided: set[str]) -> int:
    done = sum(1 for d in REQUIRED if d.key in provided)
    return round(100 * done / len(REQUIRED)) if REQUIRED else 0


def conclusion(provided: set[str]) -> str:
    """Заключение для покупателя простым языком."""
    pct = percent(provided)
    done = [d for d in REQUIRED if d.key in provided]
    missing = [d for d in REQUIRED if d.key not in provided]

    lines = [f"📋 <b>Ваш результат: собрано {len(done)} из {len(REQUIRED)} ({pct}%)</b>", ""]

    if done:
        lines.append("✅ <b>Вы предоставили:</b>")
        lines += [f"• {d.title}" for d in done]
        lines.append("")

    if missing:
        lines.append("⚠️ <b>Не хватает фотографий — на что обратить внимание:</b>")
        for d in missing:
            lines.append(f"• <b>{d.title}</b> — {d.risk}")
        lines.append("")

    lines.append("ℹ️ Важно: наличие документов — это уже хорошо, но мы ещё проверяем их "
                 "<b>содержание</b>. Фотография подтверждает, что документ есть, а дальше "
                 "каждую строку нужно изучить.")
    lines.append("")

    if pct >= OFFER_THRESHOLD:
        lines.append("🎉 <b>Вы собрали почти всё!</b> Получите от нас <b>проверку документов, "
                     "консультацию, заключение и сопровождение до госрегистра со скидкой 50%</b>.\n"
                     "Оставьте имя и телефон — мы свяжемся с вами.")
    else:
        lines.append("Соберите недостающие документы у застройщика и пройдите проверку ещё раз — "
                     "чем полнее пакет, тем безопаснее покупка.")
    return "\n".join(lines)
